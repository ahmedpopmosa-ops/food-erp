export type Locale = 'ar' | 'en';

interface I18n {
  locale: Locale;
  t: Dict;
  setLocale: (l: Locale) => void;
  money: (amount: string | number, currency?: string) => string;
  /** A unit price or cost: like money, but keeps up to 6 decimals (0.018 per g stays 0.018). */
  price: (amount: string | number, currency?: string) => string;
  dateTime: (iso: string) => string;
  /** Calendar date of a DATE column or ISO timestamp (no time). */
  date: (iso: string) => string;
  /** Quantity with up to 3 decimals and a translated unit, e.g. "1.5 kg". */
  quantity: (qty: string, unit: string) => string;
  /** Picks nameAr/nameEn for the current locale. */
  name: (row: { nameAr?: string | null; nameEn?: string | null }) => string;
  error: (code: string | undefined) => string;
}

const Ctx = createContext<I18n | null>(null);

const stored = (): Locale => {
  try {
    return localStorage.getItem('ros.locale') === 'en' ? 'en' : 'ar';
  } catch {
    return 'ar';
  }
};

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(stored);
  useEffect(() => {
    document.documentElement.lang = locale;
    document.documentElement.dir = locale === 'ar' ? 'rtl' : 'ltr';
  }, [locale]);
  const value = useMemo<I18n>(() => {
    const tag = locale === 'ar' ? 'ar-EG' : 'en-EG';
    return {
      locale,
      t: locale === 'ar' ? ar : en,
      setLocale: (l) => {
        try {
          localStorage.setItem('ros.locale', l);
        } catch {
          /* per-viewer convenience only */
        }
        setLocaleState(l);
      },
      // Display only: Number() is acceptable for formatting, never for arithmetic (ADR-0006).
      money: (amount, currency = 'EGP') =>
        new Intl.NumberFormat(tag, { style: 'currency', currency }).format(Number(amount)),
      price: (amount, currency = 'EGP') =>
        new Intl.NumberFormat(tag, { style: 'currency', currency, maximumFractionDigits: 6 }).format(Number(amount)),
      dateTime: (iso) =>
        new Intl.DateTimeFormat(tag, { dateStyle: 'medium', timeStyle: 'short', timeZone: 'Africa/Cairo' }).format(
          new Date(iso),
        ),
      date: (iso) =>
        new Intl.DateTimeFormat(tag, {
          dateStyle: 'medium',
          timeZone: iso.length === 10 ? 'UTC' : 'Africa/Cairo',
        }).format(new Date(iso.length === 10 ? `${iso}T00:00:00Z` : iso)),
      quantity: (qty, unit) =>
        `${new Intl.NumberFormat(tag, { maximumFractionDigits: 3 }).format(Number(qty))} ${(locale === 'ar' ? ar : en).units[unit] ?? unit}`,
      name: (row) => (locale === 'ar' ? row.nameAr || row.nameEn : row.nameEn || row.nameAr) ?? '',
      error: (code) => {
        const d = (locale === 'ar' ? ar : en).errors;
        return (code && d[code]) || d.unknown!;
      },
    };
  }, [locale]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n() {
  const v = useContext(Ctx);
  if (!v) throw new Error('useI18n outside I18nProvider');
  return v;
}
